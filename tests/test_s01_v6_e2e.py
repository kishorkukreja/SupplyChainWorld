class AllTwentyFiveEpisodes(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        hand = demo.load_hand()
        cls.fixtures = demo.load_fixtures()
        cls.episodes = {f['fixture_id']: {p: demo.run_episode(f, p, hand) for p in POLICIES_V6} for f in cls.fixtures}

    def each(self):
        for fid, per_policy in self.episodes.items():
            for policy, ep in per_policy.items():
                with self.subTest(fixture=fid, policy=policy):
                    yield fid, policy, ep

    def test_there_are_25_episodes_and_all_complete(self):
        self.assertEqual(sum(len(v) for v in self.episodes.values()), 25)
        for _, _, ep in self.each():
            self.assertEqual(ep['transcript']['status'], 'complete')

    def test_simulator_checker_and_hand_ledgers_agree_on_all_25(self):
        for _, _, ep in self.each():
            self.assertEqual(ep['report'].violations, [])
            self.assertTrue(ep['report'].complete)
            self.assertEqual(ep['report'].scorecard, ep['scorecard'], 'the checker derived a different scorecard than the simulator')
            self.assertEqual(ep['hand'], {'ledger': True, 'metrics': True, 'tiers': True})

    def test_replay_and_the_leak_scan_pass_on_all_25(self):
        for _, _, ep in self.each():
            r = ep['replay']
            self.assertTrue(r['transcript_reproduced'], r['differences'])
            self.assertTrue(r['state_sequence_identical'] and r['replayed_scorecard_identical'] and r['replayed_history_feasible'])
            self.assertEqual(ep['leaks'], [])

    def test_every_corruption_case_is_rejected_as_expected_on_all_25(self):
        for _, _, ep in self.each():
            bad = [t['case'] for t in ep['tamper'] if not t['rejected_as_expected']]
            self.assertEqual(bad, [])
            self.assertGreaterEqual(len(ep['tamper']), 14)

    def test_the_paired_warned_scenarios_look_identical_until_the_firm_notice(self):
        self.assertTrue(all(demo.paired_identical(self.episodes).values()))

    def test_policies_are_reported_per_metric_with_no_overall_winner(self):
        for fid, per_policy in self.episodes.items():
            c = demo.compare_policies(per_policy)
            self.assertEqual(len(c['metrics']), 13)
            self.assertNotIn('winner', json.dumps(c).replace('No overall winner is declared', ''))

    def test_the_gates_are_evidence_produced_and_the_last_is_never_called_passed(self):
        packet = demo.build_packet()
        self.assertTrue(all(packet['gates'][f'G{i}']['pass'] is True for i in range(1, 9)), packet['gates'])
        self.assertIsNone(packet['gates']['G9']['pass'])


class JsonOnlyToolAgent(unittest.TestCase):
    def test_an_agent_that_only_sees_json_text_completes_a_feasible_verified_replayable_episode(self):
        for f in V6.fixtures():
            scenario, horizon = fixture_scenario(V6, f)
            runner = V6.runner(scenario, horizon)
            policy = V6.scripted('combo_on_alert')

            def agent(view):
                seen = json.loads(json.dumps(view))                       # the agent gets text, not objects
                call = policy(seen)
                return None if call is None else json.loads(json.dumps(call))
            transcript = runner.run(agent)
            w = runner._world
            self.assertEqual(transcript['status'], 'complete')
            report = V6.verify(V6.scenario_dict(w), w.history(), horizon, scorecard=w.scorecard(), actions=V6.actions(transcript))
            self.assertEqual(report.violations, [], f['fixture_id'])
            ok, diffs = V6.replay(transcript, V6.factory(scenario, horizon))
            self.assertTrue(ok, diffs)


class CommittedEvidence(unittest.TestCase):
    def test_the_committed_transcripts_still_replay_on_the_current_code(self):
        data = json.loads((EVIDENCE / 'transcripts.json').read_text())
        fixtures = {f['fixture_id']: f for f in demo.load_fixtures()}
        n = 0
        for fid, per_policy in data.items():
            for policy, transcript in per_policy.items():
                ok, diffs = replay_v6(transcript, demo.factory(fixtures[fid]))
                self.assertTrue(ok, (fid, policy, diffs))
                n += 1
        self.assertEqual(n, 25)

    def test_the_demo_script_regenerates_every_committed_file_byte_for_byte(self):
        with tempfile.TemporaryDirectory() as tmp:
            env = dict(os.environ, PYTHONPATH=str(ROOT / 'src'), PYTHONHASHSEED='0')
            done = subprocess.run([sys.executable, str(ROOT / 'scripts/run_dynamic_demo_v6.py'), '--out', tmp], cwd=ROOT, env=env,
                                  capture_output=True, text=True, timeout=300)
            self.assertEqual(done.returncode, 0, done.stderr)
            for name in GENERATED:
                self.assertEqual((Path(tmp) / name).read_bytes(), (EVIDENCE / name).read_bytes(), f'{name} differs from the committed file')
            self.assertEqual(sorted(p.name for p in Path(tmp).iterdir()), sorted(GENERATED))

    def test_the_committed_replay_log_says_all_25_reproduced(self):
        lines = [ln for ln in (EVIDENCE / 'replay.log').read_text().splitlines() if ' attempts=' in ln]
        self.assertEqual(len(lines), 25)
        for ln in lines:
            self.assertIn('transcript_reproduced=True state_sequence_identical=True scorecard_identical=True', ln)


class ExperienceRecord(unittest.TestCase):
    record = json.loads((EVIDENCE / 'experience-record.json').read_text())
    text = (EVIDENCE / 'experience-record.md').read_text()

    def test_the_record_carries_no_private_answer_and_no_forbidden_key(self):
        fx = next(f for f in demo.load_fixtures() if f['fixture_id'] == demo.EXPERIENCE_FIXTURE)
        self.assertEqual(demo.find_private_leaks(self.record, fx['scenario']), [])
        blob = json.dumps(self.record).lower()
        for key in FORBIDDEN_KEYS:
            self.assertNotIn(f'"{key}"', blob)
        self.assertNotIn('s06-', blob)                    # the human fixture name stays outside the record
        obs = [self.record['initial_observation']] + [s['observation'] for s in self.record['steps']]
        self.assertEqual(check_observations_for_leaks(fx['scenario'], obs), [])

    def test_the_record_shows_the_conventions_block_the_agent_saw(self):
        rules = self.record['initial_observation']['rules']
        self.assertIn('conventions', rules)
        for step in self.record['steps']:
            self.assertEqual(step['observation']['rules']['conventions'], rules['conventions'])

    def test_the_structural_readability_check_passes_on_the_committed_record(self):
        self.assertEqual(demo.readability_check(self.record, self.text), [])
        saved = json.loads((EVIDENCE / 'readability-check.json').read_text())
        self.assertEqual(saved['problems'], [])
        self.assertIn('does not show that a person finds the record readable', saved['what_this_does_not_show'])

    def test_every_action_has_a_plain_language_line(self):
        lines = [ln for ln in self.text.splitlines() if ln.startswith('- Step ')]
        self.assertEqual(len(lines), len(self.record['steps']))
        for step, ln in zip(self.record['steps'], lines):
            self.assertIn(demo.plain_action(step), ln)
            self.assertRegex(demo.plain_action(step), r'^(Chose to|Tried to|Looked at|Read the)')

    def test_the_check_is_not_vacuous_it_fails_on_damaged_records(self):
        r, t = self.record, self.text
        damaged = {
            'a section is missing': (r, t.replace('## The result', '## Outcome')),
            'an action line is missing': (r, t.replace(next(ln for ln in t.splitlines() if ln.startswith('- Step 3.')), '')),
            'a raw commit key shows': (r, t + '\nbought lot auto-0123abcd\n'),
            'a raw scenario label shows': (r, t + '\nscenario scn-0a1b2c3d\n'),
            'a fixture name shows': (r, t + '\nfixture s06-sudden-5d\n'),
            'Python object text shows': (r, t + "\n{'choice': 'expedite'}\n"),
            'a private field name shows': (r, t + '\nthe hand_ledger says\n'),
            'a step lost its plain wording': (r, t.replace('Chose to', 'Did', 1)),
        }
        for name, (rec, text) in damaged.items():
            with self.subTest(case=name):
                self.assertTrue(demo.readability_check(rec, text), f'{name}: the structural check did not notice')

    def test_the_limits_of_the_check_are_stated_where_a_reader_looks(self):
        page = (EVIDENCE / 'report.html').read_text()
        self.assertIn('does not show that a person finds the record readable', page)
        self.assertIn('does not show', demo.readability_check.__doc__.lower().replace('not show that', 'not show'))
        self.assertTrue(re.search(r'NOT show', demo.readability_check.__doc__))


