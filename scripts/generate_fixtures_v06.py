#!/usr/bin/env python3
"""Regenerate fixtures/dynamic/v0.6/scenarios.json (S01 v0.6, issue #19 audit follow-up).

The v0.6 scenarios have exactly the v0.5 numbers, rules and opaque scenario labels (the label is a hash of the visible
parameters and does not depend on the version). What changed in v0.6 is in the world and the checker, not in the
numbers: the agent-visible rules carry a conventions block, exact-once also holds when no action id is sent, and the
independent checker was rebuilt. Only the fixture id (outside the world) is renamed s05- to s06-.

This script imports NOTHING from `supplychainworld`. Its only input is the plain-data v0.5 fixture file.

Usage: python scripts/generate_fixtures_v06.py [--check]
  --check  exit nonzero if the committed scenarios.json differs from this script's output.
All numbers are PROVISIONAL, needs practitioner value. Not reviewed by a practitioner.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'fixtures/dynamic/v0.5/scenarios.json'
OUT = ROOT / 'fixtures/dynamic/v0.6/scenarios.json'


def build():
    src = json.loads(SOURCE.read_text())
    fixtures = [{'fixture_id': fx['fixture_id'].replace('s05-', 's06-', 1), 'horizon_days': fx['horizon_days'],
                 'disruption_class': fx['disruption_class'], 'scenario': dict(fx['scenario'])}
                for fx in src['fixtures']]
    basis = ('Synthetic S01 v0.6 family fixtures (issue #19, audit follow-up). Same numbers, rules and opaque scenario '
             'labels as v0.5 (fixtures/dynamic/v0.5), generated by scripts/generate_fixtures_v06.py. New in v0.6 and not '
             'visible in these numbers: a conventions block in the agent-visible rules, exact-once purchases without an '
             'action id, and a rebuilt independent checker. EVERY number is PROVISIONAL, needs practitioner value. Not '
             'reviewed by a practitioner. Penalty rate for percent_of_value is in basis points (150 = 1.5% per day). '
             'Alternate-supplier unit cost is the premium over the primary unit cost only; the base purchase cost of a '
             'recovery lot is cost-neutral and alternate-bought surplus earns no salvage (unresolved assumption, see '
             'docs/acceptance/dynamic-v0.4-provisional-values.md).')
    return {'basis': basis, 'fixtures': fixtures}


def main():
    text = json.dumps(build(), indent=1) + '\n'
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('scenarios.json differs from the generator output', file=sys.stderr)
            return 1
        print('scenarios.json matches the generator output')
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
