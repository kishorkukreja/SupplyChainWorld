#!/usr/bin/env python3
"""Generate docs/acceptance/static-v1.1-provisional-values.md from the v1.1 fixtures.

Every policy number a fixture sets is listed with the marker, so the reviewer can re-review all of them.
Run: PYTHONPATH=src python scripts/generate_static_v11_provisional_table.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'fixtures' / 'reference_cases_v1_1'
OUT = ROOT / 'docs' / 'acceptance' / 'static-v1.1-provisional-values.md'
MARK = 'PROVISIONAL, needs practitioner value'

FINDING = {
    'safety_stock': ('A1', 'Safety stock target (units) added to demand'),
    'late_inbound_tolerance_days': ('A1', 'Late-inbound tolerance window (days after item deadline)'),
    'late_inbound_credit': ('A1', 'Fraction of a late inbound line counted (floor to whole units)'),
    'concentration': ('A2', 'Concentration limit (measure declared per task)'),
    'cost_tolerance_abs': ('A3', 'Equivalent-to-optimal band, absolute USD'),
    'cost_tolerance_pct': ('A3', 'Equivalent-to-optimal band, fraction of optimum'),
    'reliability_score': ('A3', 'Supplier reliability score (report-only metric)'),
    'lead_time_risk': ('A3', 'Quote lead-time risk (report-only metric)'),
    'approval_limit': ('A4', 'Approval limit in USD (estimate allowed only strictly below)'),
    'critical': ('A4', 'Part is critical (estimate never allowed)'),
    'last_known': ('A4', 'Last known price or freight used for a flagged estimate'),
    'fixed_charge': ('A5', 'Fixed supplier charge (flat or table row, USD)'),
    'excess_allowance': ('A6', 'Explicit permitted excess units'),
    'moq_excess_allowed': ('A6', 'MOQ may justify excess (flag required)'),
    'max_excess': ('A6', 'Shelf-life / obsolescence cap on all excess (units)'),
}


def rows_for(case_id, w):
    out = []

    def add(key, where, value):
        finding, meaning = FINDING[key]
        out.append((case_id, finding, f'{where}', meaning, value))

    for item in w['items']:
        for key in ('safety_stock', 'excess_allowance', 'max_excess'):
            if item[key] not in (0, None):
                add(key, f"items.{item['item_id']}.{key}", item[key])
        if item['critical']:
            add('critical', f"items.{item['item_id']}.critical", 'true')
        if item['moq_excess_allowed']:
            add('moq_excess_allowed', f"items.{item['item_id']}.moq_excess_allowed", 'true')
    for key, value in w['policy'].items():
        if key != 'schema_version' and str(value) not in ('0', '0.0'):
            add(key, f'policy.{key}', value)
    if w['constraints']['approval_limit'] is not None:
        add('approval_limit', 'constraints.approval_limit', w['constraints']['approval_limit'])
    for n, rule in enumerate(w['constraints']['concentration']):
        add('concentration', f"constraints.concentration[{n}] {rule['measure']}", rule['limit'])
    for s in w['suppliers']:
        sid = s['supplier_id']
        if s['reliability_score'] is not None:
            add('reliability_score', f'suppliers.{sid}.reliability_score', s['reliability_score'])
        if s['fixed_charge'] is not None and s['fixed_charge'] != '0.00':
            add('fixed_charge', f'suppliers.{sid}.fixed_charge (flat)', s['fixed_charge'])
        for t in s['fixed_charge_table']:
            add('fixed_charge', f"suppliers.{sid}.table[{s['fixed_charge_basis']} >= {t['from_measure']}]", t['charge'])
    for q in w['quotes']:
        key = f"quotes.{q['supplier_id']}.{q['item_id']}"
        if q['lead_time_risk'] is not None:
            add('lead_time_risk', key + '.lead_time_risk', q['lead_time_risk'])
        for f in ('last_known_unit_price', 'last_known_variable_freight'):
            if q[f] is not None:
                add('last_known', f'{key}.{f}', q[f])
    return out


def render():
    lines = [
        '# Static supplier allocation 1.1: provisional values',
        '',
        '**Status: every number below is PROVISIONAL, needs practitioner value.** Reviewed by a practitioner: no. Awaiting re-review.',
        '',
        'Source: owner-practitioner review of 2026-11-16 (docs/reviews/2026-11-16-practitioner-review-17.md; not independent), '
        'findings A1 to A7, and the owner decisions recorded on issue #35. The review confirmed the rule changes, '
        'but confirmed no numeric value. The numbers here exist only so the rules can be exercised and tested. '
        'They are not practice, not benchmarks and not recommendations. Generated by '
        '`scripts/generate_static_v11_provisional_table.py` from `fixtures/reference_cases_v1_1/`; a test fails if this file drifts from the fixtures.',
        '',
        '## Structural rule choices needing confirmation',
        '',
        '| Rule | Choice made | Finding | Marker |',
        '| --- | --- | --- | --- |',
        '| Late inbound credit | Counts only when it arrives 1..tolerance days after the item deadline, at the credit fraction, floored per inbound line; tolerance edge is inclusive | A1 | ' + MARK + ' |',
        '| Held and reserved stock | Still never counts | A1 | ' + MARK + ' |',
        '| Safety stock | Added to demand before usable stock and inbound are netted | A1 | ' + MARK + ' |',
        '| Cost band | Equivalent-to-optimal if gap <= absolute band OR gap <= fraction x optimum (inclusive); exact gap always reported | A3 | ' + MARK + ' |',
        '| Non-cost factors | Reliability and lead-time risk are report-only metrics, never merged into cost or pass/fail | A3 | ' + MARK + ' |',
        '| Estimate rule | Line value (qty x (price + freight) with last known terms) must be strictly under the approval limit and the item non-critical | A4 | ' + MARK + ' |',
        '| Fixed charge basis | Table by order units or goods value; row with the largest lower bound not above the measure | A5 | ' + MARK + ' |',
        '| Rounding | Removed; exact Decimal (reviewer clarification of A5 on issue #35) | A5 | resolved by reviewer, not provisional |',
        '| MOQ excess | Excess beyond the allowance is justified only if the total equals the smallest reachable quantity at or above net, the item allows it, and it is flagged | A6 | ' + MARK + ' |',
        '| Shelf-life cap | max_excess caps all excess, including explicit allowance and MOQ excess | A6 | ' + MARK + ' |',
        '',
        '## Numeric policy values by case',
        '',
        'Prices, demands, capacities and dates are synthetic scenario inputs shown in each fixture beside its hand calculation; they carry no practice claim.',
        '',
        '| Case | Finding | Field | Meaning | Value | Marker |',
        '| --- | --- | --- | --- | --- | --- |',
    ]
    for path in sorted(FIXTURES.glob('ref-*.json')):
        c = json.loads(path.read_text())
        for case_id, finding, where, meaning, value in rows_for(c['case_id'], c['world']):
            lines.append(f'| {case_id} | {finding} | `{where}` | {meaning} | {value} | {MARK} |')
    lines += ['', 'Open values still requested from the reviewer: safety stock level, late-inbound tolerance and credit, '
              'cost tolerance, approval limit, which concentration measure applies to which real task, and fixed-charge tier tables.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f'wrote {OUT} ({len(text.splitlines())} lines)')
